"""PostgreSQL database setup for Dukaan Dost."""

from contextlib import contextmanager
import os
from pathlib import Path
from typing import Iterator

import psycopg
from dotenv import load_dotenv
from psycopg.rows import dict_row

PROJECT_ROOT = Path(__file__).resolve().parents[1]
load_dotenv(PROJECT_ROOT / ".env")

SCHEMA = """
CREATE TABLE IF NOT EXISTS shops (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::TEXT
);

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_sub TEXT NOT NULL UNIQUE,
    email TEXT NOT NULL,
    name TEXT NOT NULL,
    picture TEXT NOT NULL DEFAULT '',
    shop_id INTEGER NOT NULL UNIQUE REFERENCES shops(id) ON DELETE CASCADE,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::TEXT
);

CREATE TABLE IF NOT EXISTS auth_sessions (
    token_hash TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at INTEGER NOT NULL,
    created_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS agent_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    action TEXT NOT NULL,
    description TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::TEXT
);

CREATE TABLE IF NOT EXISTS categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    UNIQUE (id, shop_id)
);

CREATE TABLE IF NOT EXISTS items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    category_id INTEGER NOT NULL,
    UNIQUE (shop_id, name, category_id),
    FOREIGN KEY (category_id, shop_id)
        REFERENCES categories(id, shop_id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS restock_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    category_id INTEGER NOT NULL,
    UNIQUE (shop_id, name, category_id),
    FOREIGN KEY (category_id, shop_id)
        REFERENCES categories(id, shop_id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS customers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    total_paise INTEGER NOT NULL DEFAULT 0 CHECK (total_paise >= 0),
    UNIQUE (id, shop_id)
);

CREATE TABLE IF NOT EXISTS credit_records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    customer_id INTEGER NOT NULL,
    amount_paise INTEGER NOT NULL CHECK (amount_paise > 0),
    entry_date TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    FOREIGN KEY (customer_id, shop_id)
        REFERENCES customers(id, shop_id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_categories_shop_name_ci
    ON categories(shop_id, lower(name));
CREATE UNIQUE INDEX IF NOT EXISTS uq_customers_shop_name_ci
    ON customers(shop_id, lower(name));
CREATE INDEX IF NOT EXISTS idx_items_shop_category
    ON items(shop_id, category_id);
CREATE INDEX IF NOT EXISTS idx_restock_shop_category
    ON restock_items(shop_id, category_id);
CREATE INDEX IF NOT EXISTS idx_credit_shop_customer_date
    ON credit_records(shop_id, customer_id, entry_date);
CREATE INDEX IF NOT EXISTS idx_auth_sessions_user
    ON auth_sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_agent_logs_user_created
    ON agent_logs(user_id, created_at DESC, id DESC);
"""


def _database_url() -> str:
    url = os.getenv("DATABASE_URL")
    if not url:
        raise RuntimeError("DATABASE_URL is not configured")
    return url


def init_db() -> None:
    with psycopg.connect(_database_url()) as connection:
        for statement in SCHEMA.split(";"):
            if statement.strip():
                connection.execute(statement)


@contextmanager
def get_connection() -> Iterator[psycopg.Connection]:
    with psycopg.connect(_database_url(), row_factory=dict_row) as connection:
        yield connection
